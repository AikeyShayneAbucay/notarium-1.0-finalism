-- ============================================================================
-- NOTARIX 1.0 - ONLINE APPOINTMENTS TABLE, RLS POLICIES & RPC FUNCTIONS
-- Public client booking portal backed by Supabase Auth (Google OAuth).
-- Appointment reference numbers use a dedicated sequence (APT-YYYY-NNNN)
-- and are fully separate from notarization document numbers (YYYY-XXXX).
-- ============================================================================

-- 1. DEDICATED REFERENCE NUMBER SEQUENCE (never shared with records)
create sequence if not exists public.appointment_ref_seq start 1;

-- 2. APPOINTMENTS TABLE
create table if not exists public.appointments (
  id bigint generated by default as identity primary key,
  reference_no text not null unique,
  user_id uuid not null references auth.users(id) on delete cascade,
  client_name text not null,
  client_email text not null,
  contact_number text not null,
  document_type text not null,
  appointment_date date not null,
  appointment_time time not null,
  purpose text not null default '',
  status text not null default 'Pending'
    check (status in ('Pending', 'Approved', 'Rejected', 'Rescheduled', 'Completed', 'Cancelled')),
  remarks text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_appointments_slot on public.appointments (appointment_date, appointment_time);
create index if not exists idx_appointments_user_id on public.appointments (user_id);
create index if not exists idx_appointments_status on public.appointments (status);
create index if not exists idx_appointments_created_at on public.appointments (created_at desc);

-- 3. AUTO-TOUCH updated_at ON UPDATE
create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists trg_appointments_touch on public.appointments;
create trigger trg_appointments_touch
  before update on public.appointments
  for each row execute function public.touch_updated_at();

-- 4. STAFF HELPER — true when the caller is a linked Admin/Secretary profile.
--    Uses the existing profiles.auth_user_id column; existing policies untouched.
create or replace function public.is_office_staff()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles p
    where p.auth_user_id = auth.uid()
      and p.role in ('admin', 'staff')
  );
$$;

-- 5. ROW LEVEL SECURITY
alter table public.appointments enable row level security;

-- Clients can read only their own appointments; office staff can read all.
drop policy if exists "Clients read own appointments" on public.appointments;
create policy "Clients read own appointments"
  on public.appointments for select
  using (auth.uid() = user_id or public.is_office_staff());

-- Clients can create appointments only for their own authenticated account.
drop policy if exists "Clients create own appointments" on public.appointments;
create policy "Clients create own appointments"
  on public.appointments for insert
  with check (auth.uid() = user_id);

-- Only Admin/Secretary can change or delete appointments (approve, reject,
-- reschedule, complete, cancel). Clients cancel through cancel_my_appointment().
drop policy if exists "Staff manage appointments" on public.appointments;
create policy "Staff manage appointments"
  on public.appointments for update
  using (public.is_office_staff())
  with check (public.is_office_staff());

drop policy if exists "Staff delete appointments" on public.appointments;
create policy "Staff delete appointments"
  on public.appointments for delete
  using (public.is_office_staff());

-- 6. CLIENT BOOKING RPC
--    Identity (user id + email) always comes from the authenticated session.
--    Validates office rules (future date, Mon-Sat, 9:00-16:00 slot window,
--    no double booking) and generates the APT-YYYY-NNNN reference number.
create or replace function public.create_appointment(
  p_client_name text,
  p_contact_number text,
  p_document_type text,
  p_appointment_date date,
  p_appointment_time time,
  p_purpose text default ''
)
returns public.appointments
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_email text;
  v_name text;
  v_year int;
  v_seq bigint;
  v_reference text;
  v_row public.appointments;
begin
  if v_user is null then
    raise exception 'You must be signed in to book an appointment.';
  end if;

  select email into v_email from auth.users where id = v_user;
  if v_email is null then
    raise exception 'Signed-in account has no email on file.';
  end if;

  v_name := coalesce(nullif(trim(p_client_name), ''), split_part(v_email, '@', 1));

  if trim(coalesce(p_contact_number, '')) = '' then
    raise exception 'Contact number is required.';
  end if;
  if trim(coalesce(p_document_type, '')) = '' then
    raise exception 'Document type is required.';
  end if;

  if p_appointment_date is null or p_appointment_time is null then
    raise exception 'Preferred date and time are required.';
  end if;
  if p_appointment_date <= current_date then
    raise exception 'Appointment date must be a future date.';
  end if;
  if extract(dow from p_appointment_date) = 0 then
    raise exception 'The office is closed on Sundays. Please choose another date.';
  end if;
  if p_appointment_time < '09:00'::time or p_appointment_time > '16:00'::time then
    raise exception 'Bookings are only available from 9:00 AM to 4:00 PM.';
  end if;
  if extract(minute from p_appointment_time) not in (0, 30) or extract(second from p_appointment_time) <> 0 then
    raise exception 'Appointments must be booked in 30-minute intervals.';
  end if;

  if exists (
    select 1 from public.appointments a
    where a.appointment_date = p_appointment_date
      and a.appointment_time = p_appointment_time
      and a.status in ('Pending', 'Approved', 'Rescheduled')
  ) then
    raise exception 'That date and time is already booked. Please choose another slot.';
  end if;

  v_year := extract(year from p_appointment_date);
  v_seq := nextval('public.appointment_ref_seq');
  v_reference := 'APT-' || v_year || '-' || lpad(v_seq::text, 4, '0');

  insert into public.appointments (
    reference_no,
    user_id,
    client_name,
    client_email,
    contact_number,
    document_type,
    appointment_date,
    appointment_time,
    purpose,
    status
  ) values (
    v_reference,
    v_user,
    v_name,
    v_email,
    trim(p_contact_number),
    trim(p_document_type),
    p_appointment_date,
    p_appointment_time,
    coalesce(trim(p_purpose), ''),
    'Pending'
  )
  returning * into v_row;

  return v_row;
end;
$$;

-- 7. CLIENT SELF-CANCEL RPC
--    Allowed only for the owner while status is Pending/Approved and the
--    appointment date has not arrived yet (office rule).
create or replace function public.cancel_my_appointment(
  p_appointment_id bigint,
  p_reason text default ''
)
returns public.appointments
language plpgsql
security definer
set search_path = public
as $$
declare
  v_row public.appointments;
begin
  if auth.uid() is null then
    raise exception 'You must be signed in to cancel an appointment.';
  end if;

  select * into v_row from public.appointments
  where id = p_appointment_id and user_id = auth.uid();

  if not found then
    raise exception 'Appointment not found.';
  end if;
  if v_row.status not in ('Pending', 'Approved') then
    raise exception 'Only pending or approved appointments can be cancelled.';
  end if;
  if v_row.appointment_date <= current_date then
    raise exception 'Appointments can only be cancelled before their scheduled date. Please contact the office.';
  end if;

  update public.appointments
  set status = 'Cancelled',
      remarks = concat_ws(' | ',
        nullif(v_row.remarks, ''),
        'Cancelled by client' || case when coalesce(trim(p_reason), '') <> ''
          then ': ' || trim(p_reason) else '' end)
  where id = p_appointment_id
  returning * into v_row;

  return v_row;
end;
$$;
