-- ============================================================================
-- NOTARIX 1.0 - ACTIVITY LOGS TABLE & ROW LEVEL SECURITY POLICIES
-- Enterprise audit trail for user logins, record actions, and report generation.
-- ============================================================================

create table if not exists public.activity_logs (
  id bigint generated by default as identity primary key,
  user_id bigint not null default 0,
  user_name text not null,
  role text not null check (role in ('admin', 'staff')),
  activity text not null,
  details text,
  device_info text not null,
  created_at timestamptz not null default now()
);

create index if not exists idx_activity_logs_user_id on public.activity_logs (user_id);
create index if not exists idx_activity_logs_role on public.activity_logs (role);
create index if not exists idx_activity_logs_created_at on public.activity_logs (created_at desc);

-- Enable Row Level Security (RLS)
alter table public.activity_logs enable row level security;

-- Policies for activity_logs:
-- Allow read access for authenticated and anonymous clients
drop policy if exists "Allow read access to activity_logs" on public.activity_logs;
create policy "Allow read access to activity_logs" on public.activity_logs for select using (true);

-- Allow insert access so logged activities can be automatically inserted
drop policy if exists "Allow insert access to activity_logs" on public.activity_logs;
create policy "Allow insert access to activity_logs" on public.activity_logs for insert with check (true);

-- Protect activity logs against unauthorized editing and deletion (immutable audit log)
drop policy if exists "Disallow update to activity_logs" on public.activity_logs;
create policy "Disallow update to activity_logs" on public.activity_logs for update using (false);

drop policy if exists "Disallow delete to activity_logs" on public.activity_logs;
create policy "Disallow delete to activity_logs" on public.activity_logs for delete using (false);
