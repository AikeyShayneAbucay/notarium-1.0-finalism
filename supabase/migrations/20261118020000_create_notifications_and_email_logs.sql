-- ============================================================================
-- NOTARIX 1.0 - IN-APP NOTIFICATIONS & TRANSACTIONAL EMAIL LOGS
-- Complete notification infrastructure for Client In-App notices and
-- automated Gmail/Email delivery tracking with deduplication.
-- ============================================================================

-- 1. NOTIFICATIONS TABLE (Client In-App Notification Center)
create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  message text not null,
  notification_type text not null,
  related_appointment_id bigint references public.appointments(id) on delete cascade,
  related_document_request_id bigint,
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists idx_notifications_user_lookup
  on public.notifications (user_id, is_read, created_at desc);

create index if not exists idx_notifications_apt_id
  on public.notifications (related_appointment_id);

-- 2. EMAIL LOGS & OUTBOX TABLE (Idempotent delivery audit & error tracking)
create table if not exists public.email_logs (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  recipient_email text not null,
  recipient_name text not null default '',
  event_type text not null,
  related_record_id text not null default '',
  unique_event_key text not null unique,
  subject text not null default '',
  email_status text not null default 'pending'
    check (email_status in ('pending', 'accepted', 'delivered', 'failed')),
  provider_message_id text,
  error_message text,
  attempt_count integer not null default 0,
  created_at timestamptz not null default now(),
  sent_at timestamptz
);

create index if not exists idx_email_logs_event_key
  on public.email_logs (unique_event_key);

create index if not exists idx_email_logs_user
  on public.email_logs (user_id);

create index if not exists idx_email_logs_status
  on public.email_logs (email_status);

create index if not exists idx_email_logs_created
  on public.email_logs (created_at desc);

-- 3. ROW LEVEL SECURITY (RLS)
alter table public.notifications enable row level security;
alter table public.email_logs enable row level security;

-- Client RLS: Clients can only see their own notifications; staff can see all
drop policy if exists "Clients select own notifications" on public.notifications;
create policy "Clients select own notifications"
  on public.notifications for select
  using (auth.uid() = user_id or public.is_office_staff());

-- Client RLS: Clients can update their own notification read status
drop policy if exists "Clients update own notifications" on public.notifications;
create policy "Clients update own notifications"
  on public.notifications for update
  using (auth.uid() = user_id or public.is_office_staff())
  with check (auth.uid() = user_id or public.is_office_staff());

-- Notification creation: Authenticated clients and staff can create notifications
drop policy if exists "Insert notifications" on public.notifications;
create policy "Insert notifications"
  on public.notifications for insert
  with check (auth.uid() = user_id or public.is_office_staff());

-- Email logs RLS: Only authorized office staff and service role can access email logs
drop policy if exists "Staff view email logs" on public.email_logs;
create policy "Staff view email logs"
  on public.email_logs for select
  using (public.is_office_staff());

drop policy if exists "Staff insert email logs" on public.email_logs;
create policy "Staff insert email logs"
  on public.email_logs for insert
  with check (public.is_office_staff());

drop policy if exists "Staff update email logs" on public.email_logs;
create policy "Staff update email logs"
  on public.email_logs for update
  using (public.is_office_staff())
  with check (public.is_office_staff());

-- 4. HELPER RPC: CREATE NOTIFICATION (Security Definer)
-- Safe invocation from staff actions or booking workflows
create or replace function public.create_client_notification(
  p_user_id uuid,
  p_title text,
  p_message text,
  p_type text,
  p_appointment_id bigint default null,
  p_document_request_id bigint default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id bigint;
begin
  insert into public.notifications (
    user_id,
    title,
    message,
    notification_type,
    related_appointment_id,
    related_document_request_id,
    is_read,
    created_at
  ) values (
    p_user_id,
    p_title,
    p_message,
    p_type,
    p_appointment_id,
    p_document_request_id,
    false,
    now()
  ) returning id into v_id;

  return v_id;
end;
$$;

-- 5. HELPER RPC: MARK ALL NOTIFICATIONS AS READ
create or replace function public.mark_all_notifications_read()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_count integer;
begin
  update public.notifications
  set is_read = true
  where user_id = auth.uid()
    and is_read = false;

  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

