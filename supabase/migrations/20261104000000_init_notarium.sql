-- 1. DOCUMENT TYPES TABLE
create table if not exists public.document_types (
  id bigint generated by default as identity primary key,
  name text not null unique,
  created_at timestamptz not null default now()
);

-- 2. NOTARIZATION RECORDS TABLE
create table if not exists public.records (
  id bigint generated by default as identity primary key,
  document_no text not null,
  type text not null,
  client_name text not null,
  date_notarized date not null default current_date,
  status text not null default 'For Submission' check (status in ('In Office', 'For Submission', 'Submitted')),
  location text not null default 'Palasan Law Office' check (location in ('Palasan Law Office', 'Main Office')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_records_document_no on public.records (document_no);
create index if not exists idx_records_date_notarized on public.records (date_notarized);
create index if not exists idx_records_status on public.records (status);

-- 3. OFFICE SETTINGS TABLE
create table if not exists public.office_settings (
  id integer primary key default 1,
  name text not null default 'Palasan Law Office',
  address text not null default 'pob. 2',
  contact text not null default '09123456789',
  updated_at timestamptz not null default now(),
  constraint single_row_settings check (id = 1)
);

-- 4. PROFILES / STAFF TABLE
create table if not exists public.profiles (
  id bigint generated by default as identity primary key,
  auth_user_id uuid references auth.users(id) on delete set null,
  name text not null,
  email text not null unique,
  role text not null default 'staff' check (role in ('admin', 'staff')),
  password text,
  created_at timestamptz not null default now()
);

-- ============================================================================
-- ROW LEVEL SECURITY (RLS) POLICIES
